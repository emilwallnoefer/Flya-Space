-- Fleet edge cases, phase 3: notices to people other than the holder.
-- Plan: web/docs/fleet-edge-cases.md (P3). Run after 2026-10-19-fleet-edge-cases-2.sql.
--
-- The next booker is told when their unit has not come back, the requester
-- when their extension was answered, the promoted person when the waitlist
-- moved, the admins when something is a week overdue. Each goes out once:
-- this table is the claim. The server INSERTs (reservation, recipient, kind,
-- date) BEFORE pushing or mailing, and the unique index refuses the second
-- attempt — same shape as fleet_reminder_sends and push_reminder_sends.
--
-- Service-role only. Safe to re-run.

create table if not exists public.fleet_notice_sends (
  id bigint generated by default as identity primary key,
  reservation_id uuid not null references public.fleet_reservations (id) on delete cascade,
  recipient_id uuid not null references auth.users (id) on delete cascade,
  -- 'unit_not_back' | 'extension_request' | 'extension_accepted' | 'extension_declined'
  --   | 'waitlist_promoted' | 'unit_back_early' | 'overdue_escalation'
  kind text not null,
  -- The day this notice is "for". Event notices use today; the two-day
  -- warning uses the next booking's start minus two, so it goes once however
  -- many mornings fall in that window.
  sent_for_date date not null,
  -- 'sending' | 'pushed' | 'emailed' | 'opted_out' | 'no_channel' | 'failed'
  status text not null default 'sending',
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists fleet_notice_sends_once
  on public.fleet_notice_sends (reservation_id, recipient_id, kind, sent_for_date);

create index if not exists fleet_notice_sends_recipient_idx
  on public.fleet_notice_sends (recipient_id, created_at desc);

alter table public.fleet_notice_sends enable row level security;
revoke all on table public.fleet_notice_sends from public, anon, authenticated;
grant all on table public.fleet_notice_sends to service_role;
