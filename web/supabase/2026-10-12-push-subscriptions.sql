-- Phone (Web Push) notifications. Apply by hand in the SQL editor; safe to re-run.
--
-- Two tables:
--   push_subscriptions   — one row per browser/device that opted in from
--                          Settings → Notifications. The endpoint is the push
--                          service's URL for that device; `p256dh` and `auth`
--                          are the keys the browser minted so only it can read
--                          what we send (RFC 8291). They identify a device, not
--                          a person, so they stay behind RLS: a user sees and
--                          removes only their own rows, nobody else's.
--   push_reminder_sends  — the claim that stops a reminder going out twice.
--                          The Friday cron inserts (user, kind, week) BEFORE
--                          sending, and the unique index refuses the second
--                          attempt, so a retried or double-fired cron cannot
--                          notify the same phone twice for the same week.
--                          Written by the service role only.
--
-- `public.has_app_role()` on every policy: a held account (no role yet) may
-- not register a device — see CLAUDE.md on the role gate not being the boundary.

begin;

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  endpoint text not null,
  p256dh text not null,
  auth text not null,
  -- Browser UA at subscription time, for the "your devices" list later and
  -- for telling an iPhone from a laptop in the audit trail. Free text, never
  -- trusted for anything.
  user_agent text,
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  constraint push_subscriptions_endpoint_unique unique (endpoint),
  constraint push_subscriptions_endpoint_https check (endpoint like 'https://%'),
  constraint push_subscriptions_endpoint_len check (char_length(endpoint) <= 2048),
  constraint push_subscriptions_keys_len check (char_length(p256dh) <= 256 and char_length(auth) <= 128)
);

create index if not exists push_subscriptions_user_idx on public.push_subscriptions (user_id);

alter table public.push_subscriptions enable row level security;

drop policy if exists "push_subscriptions_select_own" on public.push_subscriptions;
create policy "push_subscriptions_select_own"
  on public.push_subscriptions for select
  to authenticated
  using (auth.uid() = user_id and public.has_app_role());

drop policy if exists "push_subscriptions_insert_own" on public.push_subscriptions;
create policy "push_subscriptions_insert_own"
  on public.push_subscriptions for insert
  to authenticated
  with check (auth.uid() = user_id and public.has_app_role());

drop policy if exists "push_subscriptions_update_own" on public.push_subscriptions;
create policy "push_subscriptions_update_own"
  on public.push_subscriptions for update
  to authenticated
  using (auth.uid() = user_id and public.has_app_role())
  with check (auth.uid() = user_id and public.has_app_role());

drop policy if exists "push_subscriptions_delete_own" on public.push_subscriptions;
create policy "push_subscriptions_delete_own"
  on public.push_subscriptions for delete
  to authenticated
  using (auth.uid() = user_id and public.has_app_role());

grant select, insert, update, delete on public.push_subscriptions to authenticated;
revoke all on public.push_subscriptions from anon;

-- ---------------------------------------------------------------------------

create table if not exists public.push_reminder_sends (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  -- What was sent: 'week_unlogged' is the Friday-evening "nothing logged this
  -- week" reminder. New kinds get a new value; the index keys on it.
  kind text not null,
  -- The Monday of the week the reminder is about.
  week_start date not null,
  -- How many devices were reached, and how many of the user's subscriptions
  -- came back 404/410 and were removed.
  sent_count integer not null default 0,
  gone_count integer not null default 0,
  failed_count integer not null default 0,
  mode text not null default 'cron',
  forced boolean not null default false,
  created_at timestamptz not null default now(),
  constraint push_reminder_sends_mode_check check (mode in ('cron', 'admin'))
);

create unique index if not exists push_reminder_sends_once
  on public.push_reminder_sends (user_id, kind, week_start);

alter table public.push_reminder_sends enable row level security;
-- No policies on purpose: the service role (which bypasses RLS) is the only
-- reader and writer.
revoke all on public.push_reminder_sends from anon, authenticated;

commit;
